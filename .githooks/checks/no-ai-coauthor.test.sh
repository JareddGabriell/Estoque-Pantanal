#!/usr/bin/env bash
# Tests for no-ai-coauthor.sh.
here=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=../lib/testlib.sh
source "$here/../lib/testlib.sh"
check="$here/no-ai-coauthor.sh"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp" "${repo:-}"' EXIT

msg() { printf '%s\n' "$2" > "$tmp/$1"; printf '%s\n' "$tmp/$1"; }

# Clean messages.
expect_pass "message without trailers" "$check" --file "$(msg clean1 $'feat(sync): add outbox\n\nWhy: retries.\n\nRefs: #12')"
expect_pass "human co-author" "$check" --file "$(msg clean2 $'fix: round up\n\nCo-authored-by: Maria Souza <maria@example.com>')"
expect_pass "name containing ai letters" "$check" --file "$(msg clean3 $'fix: round up\n\nCo-authored-by: Kai Moraes <kai@example.com>')"
expect_pass "prose mentioning Claude Code" "$check" --file "$(msg clean4 $'chore: configure Claude Code hooks\n\nThe Stop hook runs unit tests.')"
expect_pass "generated by a build tool" "$check" --file "$(msg clean5 $'build: regenerate wrapper\n\nGenerated by gradle wrapper task.')"
expect_pass "comment lines are ignored" "$check" --file "$(msg clean6 $'docs: fix typo\n# Co-Authored-By: Claude <noreply@anthropic.com>')"

# Messages with AI attribution.
expect_fail "Claude co-author trailer" "$check" --file "$(msg bad1 $'feat: add login\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>')"
expect_fail "lowercase trailer key" "$check" --file "$(msg bad2 $'feat: add login\n\nco-authored-by: GitHub Copilot <copilot@github.com>')"
expect_fail "ChatGPT co-author" "$check" --file "$(msg bad3 $'feat: add login\n\nCo-authored-by: ChatGPT <bot@example.com>')"
expect_fail "Assisted-by trailer" "$check" --file "$(msg bad4 $'feat: add login\n\nAssisted-by: Gemini')"
expect_fail "generic AI co-author" "$check" --file "$(msg bad5 $'feat: add login\n\nCo-authored-by: AI Assistant <x@example.com>')"
expect_fail "vendor noreply address" "$check" --file "$(msg bad6 $'feat: add login\n\nThanks noreply@anthropic.com')"
expect_fail "Generated with Claude Code line" "$check" --file "$(msg bad7 $'feat: add login\n\nGenerated with [Claude Code](https://claude.com/claude-code)')"
expect_fail "Generated by ChatGPT line" "$check" --file "$(msg bad8 $'feat: add login\n\nGenerated by ChatGPT')"
expect_fail "stdin input" bash -c 'printf "%s\n" "feat: x" "" "Co-Authored-By: Claude <noreply@anthropic.com>" | "$1" --file -' _ "$check"
expect_pass "clean stdin input" bash -c 'printf "%s\n" "feat: x" "" "Body." | "$1" --file -' _ "$check"
expect_status 2 "usage error without arguments" "$check"

# --range mode.
repo=$(make_repo)
commit_with_message "$repo" "chore: initial commit"
base=$(git -C "$repo" rev-parse HEAD)
commit_with_message "$repo" $'feat: add outbox\n\nRefs: #3'
expect_pass "--range with clean messages" bash -c 'cd "$1" && "$2" --range "$3..HEAD"' _ "$repo" "$check" "$base"
commit_with_message "$repo" $'fix: retry\n\nCo-Authored-By: Claude <noreply@anthropic.com>'
expect_fail "--range with an AI co-author" bash -c 'cd "$1" && "$2" --range "$3..HEAD"' _ "$repo" "$check" "$base"

finish
